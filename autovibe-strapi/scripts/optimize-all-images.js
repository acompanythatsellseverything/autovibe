#!/usr/bin/env node
'use strict';

/**
 * ============================================================================
 * optimize-all-images.js — Production image optimizer for Strapi v5
 * ============================================================================
 *
 * Processes ALL uploaded images (originals + responsive formats) using Sharp.
 * Optimizes in-place while keeping filenames/URLs stable.
 *
 * Features:
 *   - Backs up originals before overwriting
 *   - DRY_RUN mode to preview without changes
 *   - Optimizes originals + responsive variants (thumbnail_, small_, medium_, large_)
 *   - Updates Strapi DB file size records
 *   - Skips already-optimized files (via marker + size check)
 *   - Handles JPEG, PNG, WebP; skips non-image files
 *   - Continues on per-file errors
 *   - Detailed summary at the end
 *
 * Environment flags:
 *   DRY_RUN=true          Preview only, no writes (default: false)
 *   SKIP_BACKUP=true      Skip backup creation (default: false)
 *   MAX_WIDTH=2560        Max pixel width for originals (default: 2560)
 *   JPEG_QUALITY=82       JPEG quality 1-100 (default: 82)
 *   PNG_QUALITY=82        PNG quality 1-100 (default: 82)
 *   WEBP_QUALITY=80       WebP quality 1-100 (default: 80)
 *
 * Usage:
 *   node scripts/optimize-all-images.js
 *   DRY_RUN=true node scripts/optimize-all-images.js
 *
 * ============================================================================
 */

const path = require('path');
const fs = require('fs');
const sharp = require('sharp');

// ---------------------------------------------------------------------------
// Configuration
// ---------------------------------------------------------------------------

const DRY_RUN = process.env.DRY_RUN === 'true';
const SKIP_BACKUP = process.env.SKIP_BACKUP === 'true';

const MAX_WIDTH = parseInt(process.env.MAX_WIDTH, 10) || 2560;
const JPEG_QUALITY = parseInt(process.env.JPEG_QUALITY, 10) || 82;
const PNG_QUALITY = parseInt(process.env.PNG_QUALITY, 10) || 82;
const WEBP_QUALITY = parseInt(process.env.WEBP_QUALITY, 10) || 80;

// Responsive variant prefixes generated by Strapi
const VARIANT_PREFIXES = ['thumbnail_', 'small_', 'medium_', 'large_'];

// Max dimensions per variant (Strapi defaults)
const VARIANT_MAX = {
  thumbnail_: 245,
  small_: 500,
  medium_: 750,
  large_: 1000,
};

// Minimum bytes saved to consider optimization worthwhile (skip if < 1KB saved)
const MIN_SAVINGS_BYTES = 1024;

// Image extensions we process
const IMAGE_EXTENSIONS = new Set(['.jpg', '.jpeg', '.png', '.webp']);

// Marker file to track that optimization was already done
const MARKER_FILE = '.images-optimized';

const FILE_MODEL_UID = 'plugin::upload.file';

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`;
  if (bytes < 1024 * 1024) return `${(bytes / 1024).toFixed(1)} KB`;
  return `${(bytes / (1024 * 1024)).toFixed(2)} MB`;
}

function isImageFile(filename) {
  const ext = path.extname(filename).toLowerCase();
  return IMAGE_EXTENSIONS.has(ext);
}

function getVariantPrefix(filename) {
  for (const prefix of VARIANT_PREFIXES) {
    if (filename.startsWith(prefix)) return prefix;
  }
  return null;
}

/**
 * Optimize a single image file on disk.
 * Returns { savedBytes, newSize } or null if skipped.
 */
async function optimizeFile(filePath, maxDimension) {
  const ext = path.extname(filePath).toLowerCase();
  const originalSize = fs.statSync(filePath).size;

  const metadata = await sharp(filePath).metadata();
  const { width, height } = metadata;

  // Determine if resize is needed
  const needsResize = width && height && (width > maxDimension || height > maxDimension);

  let pipeline = sharp(filePath, { failOn: 'none' });

  // Only resize if image exceeds max dimension — never upscale
  if (needsResize) {
    pipeline = pipeline.resize(maxDimension, maxDimension, {
      fit: 'inside',
      withoutEnlargement: true,
    });
  }

  // Strip metadata (EXIF, ICC profile for non-web, etc.) to save bytes
  // Keep sRGB ICC profile for color accuracy
  pipeline = pipeline.rotate(); // auto-rotate based on EXIF, then strip

  // Format-specific optimization
  if (ext === '.jpg' || ext === '.jpeg') {
    pipeline = pipeline.jpeg({
      quality: JPEG_QUALITY,
      mozjpeg: true,        // better compression at same quality
      progressive: true,    // faster perceived loading
    });
  } else if (ext === '.png') {
    pipeline = pipeline.png({
      quality: PNG_QUALITY,
      compressionLevel: 9,  // max zlib compression
      effort: 10,           // max optimization effort
      palette: true,        // use palette if possible (huge savings for simple PNGs)
    });
  } else if (ext === '.webp') {
    pipeline = pipeline.webp({
      quality: WEBP_QUALITY,
      effort: 6,
    });
  } else {
    return null; // unsupported format
  }

  const { data, info } = await pipeline.toBuffer({ resolveWithObject: true });

  // Only write if we actually saved meaningful bytes
  if (originalSize - data.length < MIN_SAVINGS_BYTES) {
    return null; // not worth it
  }

  return {
    buffer: data,
    savedBytes: originalSize - data.length,
    newSize: data.length,
    originalSize,
    width: info.width,
    height: info.height,
  };
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------

async function run() {
  console.log('='.repeat(70));
  console.log('  Strapi Image Optimizer');
  console.log('='.repeat(70));
  console.log('');

  if (DRY_RUN) {
    console.log('  *** DRY RUN MODE — no files will be modified ***');
    console.log('');
  }

  console.log(`  Settings:`);
  console.log(`    Max width (originals): ${MAX_WIDTH}px`);
  console.log(`    JPEG quality: ${JPEG_QUALITY}`);
  console.log(`    PNG quality:  ${PNG_QUALITY}`);
  console.log(`    WebP quality: ${WEBP_QUALITY}`);
  console.log('');

  // ── Load Strapi ──────────────────────────────────────────────────────────

  const appRoot = path.resolve(__dirname, '..');
  process.chdir(appRoot);

  console.log('Loading Strapi...');
  const { createStrapi } = require('@strapi/strapi');
  const strapi = createStrapi({
    appDir: appRoot,
    distDir: path.join(appRoot, 'dist'),
  });

  try {
    await strapi.load();
  } catch (err) {
    console.error('Failed to load Strapi:', err);
    process.exit(1);
  }

  // ── Verify local storage ────────────────────────────────────────────────

  const uploadsDir = path.join(strapi.dirs.static.public, 'uploads');
  if (!fs.existsSync(uploadsDir)) {
    console.error(`Uploads directory not found: ${uploadsDir}`);
    console.error('This script only works with local file storage.');
    await strapi.destroy();
    process.exit(1);
  }

  console.log(`Uploads directory: ${uploadsDir}`);
  console.log('');

  // ── Backup ──────────────────────────────────────────────────────────────

  const backupDir = path.join(appRoot, 'backups', `uploads-backup-${Date.now()}`);

  if (!DRY_RUN && !SKIP_BACKUP) {
    console.log(`Creating backup at: ${backupDir}`);
    fs.mkdirSync(backupDir, { recursive: true });

    const allFiles = fs.readdirSync(uploadsDir);
    let backedUp = 0;
    for (const file of allFiles) {
      if (file === '.gitkeep' || file === '.DS_Store') continue;
      const src = path.join(uploadsDir, file);
      const stat = fs.statSync(src);
      if (!stat.isFile()) continue;
      fs.copyFileSync(src, path.join(backupDir, file));
      backedUp++;
    }
    console.log(`Backed up ${backedUp} files (${formatBytes(getTotalSize(backupDir))})`);
    console.log('');
  } else if (!DRY_RUN && SKIP_BACKUP) {
    console.log('WARNING: Backup skipped (SKIP_BACKUP=true)');
    console.log('');
  }

  // ── Query all files from Strapi DB ──────────────────────────────────────

  console.log('Querying upload files from database...');
  let dbFiles;
  try {
    dbFiles = await strapi.db.query(FILE_MODEL_UID).findMany({
      limit: 10000,
    });
  } catch (err) {
    console.error('Failed to query files:', err);
    await strapi.destroy();
    process.exit(1);
  }

  console.log(`Found ${dbFiles.length} file records in database`);
  console.log('');

  // ── Build map of DB files by hash for quick lookup ──────────────────────

  const dbFileByHash = new Map();
  for (const f of dbFiles) {
    if (f.hash) {
      dbFileByHash.set(f.hash, f);
    }
  }

  // ── Process all image files on disk ─────────────────────────────────────

  const diskFiles = fs.readdirSync(uploadsDir).filter((f) => {
    if (f.startsWith('.')) return false;
    return isImageFile(f);
  });

  console.log(`Found ${diskFiles.length} image files on disk`);
  console.log('-'.repeat(70));

  let totalProcessed = 0;
  let totalSkipped = 0;
  let totalErrors = 0;
  let totalBytesSaved = 0;
  let totalOriginalBytes = 0;

  // Separate originals and variants
  const originals = [];
  const variants = [];

  for (const file of diskFiles) {
    if (getVariantPrefix(file)) {
      variants.push(file);
    } else {
      originals.push(file);
    }
  }

  console.log(`  Originals: ${originals.length}, Variants: ${variants.length}`);
  console.log('');

  // ── Process originals ───────────────────────────────────────────────────

  console.log('Processing originals...');
  for (const filename of originals) {
    const filePath = path.join(uploadsDir, filename);

    try {
      const result = await optimizeFile(filePath, MAX_WIDTH);

      if (result === null) {
        totalSkipped++;
        continue;
      }

      const { buffer, savedBytes, newSize, originalSize, width, height } = result;
      totalBytesSaved += savedBytes;
      totalOriginalBytes += originalSize;

      console.log(
        `  [ok] ${filename}  ${formatBytes(originalSize)} -> ${formatBytes(newSize)}  (saved ${formatBytes(savedBytes)})`
      );

      if (!DRY_RUN) {
        fs.writeFileSync(filePath, buffer);

        // Update DB record if we have one
        const baseName = path.basename(filename, path.extname(filename));
        // Strapi hash is the filename without extension
        const dbFile = dbFileByHash.get(baseName);
        if (dbFile) {
          const sizeKb = newSize / 1024;
          await strapi.db.query(FILE_MODEL_UID).update({
            where: { id: dbFile.id },
            data: {
              size: parseFloat(sizeKb.toFixed(2)),
              width: width,
              height: height,
            },
          });
        }
      }

      totalProcessed++;
    } catch (err) {
      console.error(`  [error] ${filename}: ${err.message}`);
      totalErrors++;
    }
  }

  // ── Process variants (thumbnail_, small_, medium_, large_) ──────────────

  console.log('');
  console.log('Processing responsive variants...');
  for (const filename of variants) {
    const filePath = path.join(uploadsDir, filename);
    const prefix = getVariantPrefix(filename);
    const maxDim = VARIANT_MAX[prefix] || MAX_WIDTH;

    try {
      const result = await optimizeFile(filePath, maxDim);

      if (result === null) {
        totalSkipped++;
        continue;
      }

      const { buffer, savedBytes, newSize, originalSize, width, height } = result;
      totalBytesSaved += savedBytes;
      totalOriginalBytes += originalSize;

      console.log(
        `  [ok] ${filename}  ${formatBytes(originalSize)} -> ${formatBytes(newSize)}  (saved ${formatBytes(savedBytes)})`
      );

      if (!DRY_RUN) {
        fs.writeFileSync(filePath, buffer);

        // Update responsive format metadata in DB
        // Strapi stores variants in the `formats` JSON column of the parent file record
        const baseFilename = filename.slice(prefix.length);
        const baseHash = path.basename(baseFilename, path.extname(baseFilename));
        const dbFile = dbFileByHash.get(baseHash);

        if (dbFile && dbFile.formats) {
          const formatKey = prefix.replace('_', ''); // e.g. "thumbnail"
          const formats = typeof dbFile.formats === 'string'
            ? JSON.parse(dbFile.formats)
            : { ...dbFile.formats };

          if (formats[formatKey]) {
            formats[formatKey].size = parseFloat((newSize / 1024).toFixed(2));
            formats[formatKey].width = width;
            formats[formatKey].height = height;

            await strapi.db.query(FILE_MODEL_UID).update({
              where: { id: dbFile.id },
              data: { formats },
            });
          }
        }
      }

      totalProcessed++;
    } catch (err) {
      console.error(`  [error] ${filename}: ${err.message}`);
      totalErrors++;
    }
  }

  // ── Summary ─────────────────────────────────────────────────────────────

  console.log('');
  console.log('='.repeat(70));
  console.log('  SUMMARY');
  console.log('='.repeat(70));
  console.log(`  Mode:       ${DRY_RUN ? 'DRY RUN (no changes made)' : 'LIVE'}`);
  console.log(`  Processed:  ${totalProcessed}`);
  console.log(`  Skipped:    ${totalSkipped} (already optimal or savings < 1KB)`);
  console.log(`  Errors:     ${totalErrors}`);
  console.log(`  Saved:      ${formatBytes(totalBytesSaved)}`);
  if (totalOriginalBytes > 0) {
    const pct = ((totalBytesSaved / totalOriginalBytes) * 100).toFixed(1);
    console.log(`  Reduction:  ${pct}%`);
  }
  if (!DRY_RUN && !SKIP_BACKUP) {
    console.log(`  Backup at:  ${backupDir}`);
  }
  console.log('='.repeat(70));

  await strapi.destroy();
  process.exit(totalErrors > 0 ? 1 : 0);
}

function getTotalSize(dir) {
  let total = 0;
  for (const file of fs.readdirSync(dir)) {
    const stat = fs.statSync(path.join(dir, file));
    if (stat.isFile()) total += stat.size;
  }
  return total;
}

run().catch((err) => {
  console.error('Fatal error:', err);
  process.exit(1);
});
